"""
src/agents/state.py - Asterline Research Assistant
Shared State Definition for LangGraph StateGraph.

Maintains the state across Planner, Memory Manager, and Researcher agents.
"""

from typing import Any, Dict, List, Literal, Optional, TypedDict


class AgentState(TypedDict, total=False):
    """
    Shared state schema for the Asterline Multi-Agent StateGraph.
    
    Fields:
      user_id: Unique identifier for the user session (used for memory scoping).
      query: The original incoming user query or instruction.
      intent: The classified intent from the Planner ('research', 'memory', or 'hybrid').
      plan: Human-readable reasoning explaining why the Planner routed this request.
      memory_action: Operation requested for memory ('store', 'recall', 'forget', 'clear', 'none').
      memory_key: Optional key for the memory operation (e.g. 'tier', 'export_format').
      memory_value: Optional value for the memory operation (e.g. 'Enterprise', 'Parquet').
      user_memories: Key-value dictionary of personal user context loaded/updated by Memory Manager.
      retrieved_chunks: Evidence chunks retrieved by the Researcher from persistent ChromaDB.
      answer: Final answer generated by the appropriate agent (Memory Manager or Researcher).
      citations: Validated chunk IDs cited in the answer (e.g. ['sla:0', 'retention:0']).
      citations_valid: Boolean indicating whether all cited sources are authentic retrieved chunks.
      status: Workflow outcome status ('success', 'no_evidence', 'error').
      error: Optional error message if a failure occurred.
      execution_trace: Chronological list of agent node names that processed this request.
    """
    user_id: str
    query: str
    intent: Literal["research", "memory", "hybrid"]
    plan: str
    memory_action: Optional[Literal["store", "recall", "forget", "clear", "inspect", "none"]]
    memory_key: Optional[str]
    memory_value: Optional[str]
    user_memories: Dict[str, str]
    retrieved_chunks: List[Dict[str, Any]]
    answer: str
    citations: List[str]
    citations_valid: bool
    status: Literal["success", "no_evidence", "error"]
    error: Optional[str]
    execution_trace: List[str]


def create_initial_state(
    query: str,
    user_id: str = "default_user",
    user_memories: Optional[Dict[str, str]] = None,
) -> AgentState:
    """
    Factory helper to initialize an AgentState with safe defaults.
    """
    return {
        "user_id": user_id,
        "query": query.strip(),
        "intent": "research",
        "plan": "",
        "memory_action": "none",
        "memory_key": None,
        "memory_value": None,
        "user_memories": dict(user_memories) if user_memories else {},
        "retrieved_chunks": [],
        "answer": "",
        "citations": [],
        "citations_valid": False,
        "status": "success",
        "error": None,
        "execution_trace": [],
    }
